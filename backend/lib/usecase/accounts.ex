  alias Domain.Accounts
  def list do
    # やりたいことは外部のデータソースに保存している値を取り出して、それを返すこと
    # そのデータソースとやり取りするのはここで良い？否。理由はビジネスロジックで分かれていてほしいと思っているから
    # なんでビジネスロジックで分かれていてほしい？責務を分離したいから
    # どういう分離がなされている？外部サービスとアプリケーションの関心事を分けている
    # 混ざっているとどうなる？外部サービスの固有の事情がアプリケーションの関心事に入り込み、変更する際は外部サービスの事情を気にしなければいけない
